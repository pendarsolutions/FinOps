interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey) => string;
  fieldLabel: (f: string) => string;
  /** pick the fa or en variant of a backend bilingual pair */
  pick: (fa: string | null | undefined, en: string | null | undefined) => string;
}

const Ctx = createContext<I18n | null>(null);
const LANG_KEY = "finops.lang";

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === "en" || v === "fa") return v;
  } catch {
    /* ignore */
  }
  return "fa";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);

  useEffect(() => {
    const el = document.documentElement;
    el.lang = lang;
    el.dir = lang === "fa" ? "rtl" : "ltr";
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* ignore */
    }
  }, []);

  const value = useMemo<I18n>(() => {
    const i = lang === "fa" ? 0 : 1;
    return {
      lang,
      setLang,
      t: (k) => dict[k][i],
      fieldLabel: (f) => {
        const l = FIELD_LABELS[f];
        return l ? (lang === "fa" ? l[1] : l[0]) : f;
      },
      pick: (fa, en) => (lang === "fa" ? fa || en || "" : en || fa || ""),
    };
  }, [lang, setLang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const c = useContext(Ctx);
  if (!c) throw new Error("I18nProvider missing");
  return c;
}
